export function getTagIcon(key: string | null | undefined): LucideIcon | null {
  return key && Object.hasOwn(TAG_ICONS, key) ? TAG_ICONS[key] : null;
}

/** The tag's icon, or nothing when its key is unknown. */
export function TagIcon({ icon, className }: { icon: string | null | undefined; className?: string }) {
  const Icon = getTagIcon(icon);
  return Icon ? createElement(Icon, { className, 'aria-hidden': true }) : null;
}
